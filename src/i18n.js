let activeLanguage = 'de';

export function initialLanguage(value) {
  if (value === 'de' || value === 'en') return value;
  return globalThis.navigator?.language?.toLowerCase().startsWith('de') ? 'de' : 'en';
}

export function getLanguage() {
  return activeLanguage;
}

export function t(key, params = {}) {
  const text = messages[activeLanguage][key] ?? messages.de[key] ?? key;
  return text.replace(/\{(\w+)\}/g, (match, name) => Object.hasOwn(params, name) ? String(params[name]) : match);
}

export function applyLanguage(lang) {
  activeLanguage = initialLanguage(lang);
  document.documentElement.lang = activeLanguage;
  for (const element of document.querySelectorAll('[data-i18n]')) {
    element.textContent = t(element.dataset.i18n);
  }
  for (const [dataAttribute, attribute] of [
    ['data-i18n-aria', 'aria-label'],
    ['data-i18n-placeholder', 'placeholder'],
    ['data-i18n-alt', 'alt'],
  ]) {
    for (const element of document.querySelectorAll(`[${dataAttribute}]`)) {
      element.setAttribute(attribute, t(element.getAttribute(dataAttribute)));
    }
  }
  const languageSelect = document.getElementById('language');
  if (languageSelect) languageSelect.value = activeLanguage;
}
